// ==============================
// 单条配比明细（对应Excel一行配比数据）
// ==============================
export interface KLS胶丝比例 {
  发丝: string // 品牌：KL'S / FU
  色号: string // 色号：K3#、8#、12#、14#等
  /* 展示需要转为百分比 */
  比例: number // 百分比数值（0-100，支持小数）
}

// ==============================
// 色组数据（对应Excel的D/M/L三大列）
// ==============================

// ==============================
// 单条颜色主数据（对应Excel一行主数据）
// ==============================
export interface Db胶丝比例 {
  //颜色编号
  _id: {
    颜色编号: string // 如TT6/1062
    发丝种类: string // 如HL+FU
  }
  线色?: string // 线色：8#、4#（支持空字符串，如第一行无）
  D: KLS胶丝比例[] // D色配比列表（必有）
  M?: KLS胶丝比例[] // M色配比列表（可选）
  L?: KLS胶丝比例[] // L色配比列表（可选）
  颜色图片参考?: Uint8Array // 颜色图片参考（可选，支持空字符串）
  备注?: string // 备注（可选，支持空字符串）
}
