import { 沐茵丝假发成品稿 } from "../../db/Db沐茵丝假发成品稿"
import { 高针指示单Frontend } from "../model/model"

/**
 * 将 沐茵丝假发成品稿 转换为 高针指示单Frontend
 *
 * 机器规格清单_高针图：注释说明需要"按照档位整合成一个档位"展示，
 * 具体整合规则（如取哪个档位、如何合并多档位数据）待确认。
 * 当前实现取第一个档位作为占位。
 */
export function to高针指示单Frontend(稿: 沐茵丝假发成品稿): 高针指示单Frontend {
  return {
    title: {
      客户: 稿.客户,
      // TODO: 标题重量来源待确认（工程重量.完成.数值？或其他字段）
      重量: "",
      品名: 稿.品名,
      尺寸: 稿.高针指示单.尺寸,
      原料: 稿.原材料,
      CAP: 稿.CAP,
      样品编号: 稿._id,
    },
    // TODO: 高针图svg应将底图与DML标注合并渲染后输出；
    //       渲染逻辑（将 高针图.自定义数据.DML标注 写入 底图.svg）待实现。
    //       当前直接返回未经处理的底图svg。
    高针图svg: "",
    // 每个机器规格清单档位对应一条记录
    机器规格清单_高针图: 稿.制品规格书.机器规格清单.map(档位 => ({
      档位: 档位.档位,
      毛长: 档位.双针.毛长,
      长度: 档位.双针.尺数,
      形态: 档位.形态 ?? "",
      // 管径来源：美容.铝管（数字，单位待确认是否需要转为字符串格式如 "6mm"）
      // TODO: 确认铝管数值与管径字符串的格式转换规则
      管径: String(档位.美容.铝管),
      方向: 档位.美容.方向,
      备注: 档位.备注 ?? "",
    })),
    注意事项: 稿.高针指示单.注意事项,
    发型图片: 稿.头型图片,
  }
}
